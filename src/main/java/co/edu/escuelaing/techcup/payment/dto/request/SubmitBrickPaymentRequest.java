package co.edu.escuelaing.techcup.payment.dto.request;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;

@Schema(description = "Payload sent by the Payment Brick's onSubmit callback.")
public record SubmitBrickPaymentRequest(

        @Schema(description = "Mercado Pago payment method id (e.g. 'pse', 'visa', 'mastercard').", example = "pse")
        @NotBlank(message = "paymentMethodId es obligatorio")
        String paymentMethodId,

        @Schema(description = "Card token generated by the Brick (only for card payments).", example = "abc123token")
        String token,

        @Schema(description = "Number of installments (only for card payments).", example = "1")
        Integer installments,

        @Schema(description = "Payer email.", example = "payer@example.com")
        @NotBlank(message = "payerEmail es obligatorio")
        @Email(message = "payerEmail debe ser un correo válido")
        String payerEmail,

        @Schema(description = "PSE bank code (only for PSE payments).", example = "1007")
        String financialInstitution,

        @Schema(description = "Payer identification type (only for card payments).", example = "CC")
        String identificationType,

        @Schema(description = "Payer identification number (only for card payments).", example = "12345678")
        String identificationNumber) {
}
